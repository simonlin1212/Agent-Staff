def main():
    reg = json.load(open(os.path.join(AOS, "dept_registry.json"), encoding="utf-8"))
    total = 0
    for dept, info in reg.items():
        store = FeishuDataStore(app_token=info["app_token"], tables=info["tables"])
        for table in info.get("tables", {}):
            if table in DATA:
                try:
                    store.create_records(table, DATA[table])
                    total += len(DATA[table])
                    print(f"  ✓ {dept} / {table}: 灌 {len(DATA[table])} 条")
                except Exception as e:
                    print(f"  ✗ {dept} / {table}: {str(e)[:80]}")
    print(f"\n✅ 示例数据灌好({total} 条)。现在 @ agent 问「看战报」就有内容了。")


if __name__ == "__main__":
    main()
